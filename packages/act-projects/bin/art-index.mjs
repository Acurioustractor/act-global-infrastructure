#!/usr/bin/env node
// Regenerate the studio-line table in wiki/art/art-projects.md from the record
// and each piece's wiki frontmatter. Hand-written prose above and below the
// markers is kept. --check exits 1 when the file is behind (CI).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadProjects, artPieces, REPO_ROOT } from '../src/index.mjs';
import { indexWiki } from '../src/wiki.mjs';

const START = '<!-- art-index:start -->';
const END = '<!-- art-index:end -->';
const FILE = join(REPO_ROOT, 'wiki/art/art-projects.md');
const check = process.argv.includes('--check');

const { projects } = loadProjects();
const wiki = indexWiki(REPO_ROOT);
const ORDER = { exhibited: 0, active: 1, ideation: 2, concept: 3, retired: 4 };
const LABEL = { exhibited: 'Exhibited', active: 'Active', ideation: 'In development', concept: 'Concept', retired: 'Retired' };

function frontmatter(path) {
  const t = readFileSync(join(REPO_ROOT, path), 'utf8');
  const m = t.match(/^---\n([\s\S]*?)\n---\n/);
  const fm = {};
  if (!m) return fm;
  const lines = m[1].split('\n');
  for (let i = 0; i < lines.length; i++) {
    const kv = lines[i].match(/^([a-z_]+):\s*(.*)$/);
    if (!kv) continue;
    if (kv[2] === '|') {
      const buf = [];
      while (i + 1 < lines.length && lines[i + 1].startsWith('  ')) buf.push(lines[++i].slice(2));
      fm[kv[1]] = buf.join('\n');
    } else fm[kv[1]] = kv[2].replace(/^"(.*)"$/, '$1');
  }
  return fm;
}

const rows = artPieces(projects)
  .map((p) => {
    const path = p.art.wiki_path || (wiki.get(p.art.piece_slug) || [])[0];
    const fm = path ? frontmatter(path) : {};
    const link = path ? `[[${p.art.piece_slug}|${fm.title || p.name}]]` : fm.title || p.name;
    return { p, link, status: p.art.status, quote: (fm.quote || '').split('\n')[0], inside: p.art.connected_code ? projects[p.art.connected_code]?.name : '' };
  })
  .sort((a, b) => ORDER[a.status] - ORDER[b.status] || a.p.name.localeCompare(b.p.name));

const table = [
  `${START}`,
  `<!-- generated by packages/act-projects/bin/art-index.mjs from config/project-codes.json and each piece's wiki frontmatter; edit those, not this table -->`,
  '',
  `${rows.length} pieces in the studio line.`,
  '',
  '| Piece | Code | Status | Medium | Part of | In one line |',
  '|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.link} | \`${r.p.code}\` | ${LABEL[r.status]} | ${r.p.art.media.join(', ')} | ${r.inside || ''} | ${r.quote.replace(/\|/g, '/')} |`),
  '',
  `${END}`,
].join('\n');

const current = readFileSync(FILE, 'utf8');
let next;
if (current.includes(START) && current.includes(END)) {
  next = current.slice(0, current.indexOf(START)) + table + current.slice(current.indexOf(END) + END.length);
} else {
  // First run: replace the hand-kept "The Studio Line" table with the generated block.
  const head = current.indexOf('## The Studio Line');
  const tail = current.indexOf('## Canonical Homes');
  if (head < 0 || tail < 0) { console.error('art-projects.md: cannot find the Studio Line section to replace'); process.exit(2); }
  const intro = current.slice(head, current.indexOf('| Piece |', head));
  next = current.slice(0, head) + intro.trimEnd() + '\n\n' + table + '\n\n' + current.slice(tail);
}

if (next === current) { console.log(`art index: up to date (${rows.length} pieces)`); process.exit(0); }
if (check) { console.error('art index: wiki/art/art-projects.md is behind the record; run node packages/act-projects/bin/art-index.mjs'); process.exit(1); }
writeFileSync(FILE, next);
console.log(`art index: wrote ${rows.length} pieces into wiki/art/art-projects.md`);
